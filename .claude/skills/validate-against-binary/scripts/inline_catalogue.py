#!/usr/bin/env python3
"""
Mine the results of `validate_all.py` (asm_validate over every reversed hook) into a reference for reversers:

  1. Functions the ORIGINAL INLINED: hooked functions our code calls where the original has no call (they were inlined
     by MSVC). When you see their body pattern in a decompilation, call the function instead of re-typing the code.
  2. Small helpers called by the original that the repo doesn't know (operators, getters, POD ctors) - with IDB names
     and how many reversed functions call them.
  3. CRT functions the original calls (map them to std/C++ equivalents).
  4. Globals referenced by the original that have no StaticRef yet (with IDB names) - add them.
  5. Remaining float-precision mismatches (constants that differ from the binary).

  python .claude/skills/validate-against-binary/scripts/inline_catalogue.py                  # print markdown
  python .claude/skills/validate-against-binary/scripts/inline_catalogue.py --out docs/ai/InlineCatalogue.md
"""
from __future__ import annotations

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
CRT_HINTS = {
    "__ftol2": "float -> int truncation: `static_cast<int32>(f)`", "_ftol": "float -> int truncation: `static_cast<int32>(f)`",
    "_rand": "`rand()` (GTA's CRT generator - our `rand()` is a different instance)", "_floor": "`std::floor`",
    "_ceil": "`std::ceil`", "_sqrt": "`std::sqrt`", "_atan2": "`std::atan2`", "_sin": "`std::sin`", "_cos": "`std::cos`",
    "_strcmp": "`std::string_view{a} == b`", "_strncmp": "`std::string_view{a}.starts_with(b)` (check intent)",
    "_strcpy": "`strcpy_s`/`notsa::string_copy`", "_sprintf": "`sprintf`/`std::format_to` (same output!)",
    "_memcpy": "`memcpy` / struct assignment", "_memset": "`memset` / `= {}`",
}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--input", default=str(REPO / ".claude" / "cache" / "validate_all.jsonl"))
    ap.add_argument("--out")
    ap.add_argument("--top", type=int, default=40)
    args = ap.parse_args()

    recs = [json.loads(l) for l in Path(args.input).read_text(encoding="utf-8").splitlines() if l.strip()]
    inlined = Counter()
    inlined_where = defaultdict(list)
    helpers = Counter()
    helper_info: dict[str, str] = {}
    crt = Counter()
    globals_ = Counter()
    global_info: dict[str, str] = {}
    precision = []

    for r in recs:
        for name in r.get("extra", []):
            inlined[name] += 1
            if len(inlined_where[name]) < 3 and r["name"]:
                inlined_where[name].append(r["name"])
        for l in r["lines"]:
            if m := re.search(r"\[CHECK\]\s+0x([0-9A-F]+)(?: x\d+)?(?: \(tail call\))? - small leaf helper \((\d+) insns\)", l):
                helpers[m.group(1)] += 1
                helper_info.setdefault(m.group(1), f"{m.group(2)} insns")
            elif m := re.search(r"\[CHECK\]\s+0x([0-9A-F]+)(?: x\d+)? (\S+)(?: sub_[0-9A-F]+)? - ours must do the same", l):
                crt[m.group(2)] += 1
            elif m := re.search(r"\[MISSING\]\s+0x([0-9A-F]+) (.+?) \(([^)]*)\) - global without StaticRef", l):
                globals_[m.group(1)] += 1
                global_info.setdefault(m.group(1), m.group(2).replace(" [IDB]", ""))
            elif "PRECISION MISMATCH" in l:
                precision.append((r["name"], r["where"], l.split("[MISSING]")[1].split(" - ours")[0].strip(),
                                  re.search(r"ours only has ([^ ]+) \((\d+) ULP", l).groups() if "ULP" in l else ("?", "?")))

    # IDB names for helpers
    idb = {}
    exp = REPO / ".claude" / "cache" / "idb_export.json"
    if exp.exists():
        e = json.loads(exp.read_text(encoding="utf-8"))
        idb = {f["ea"]: f["dname"] for f in e["funcs"]}

    out = []
    w = out.append
    w("# Inline & dependency catalogue (generated)\n")
    w(f"Generated by `inline_catalogue.py` from `validate_all.py`: static validation of **{len(recs)} reversed functions** against "
      f"gta_sa.exe. **Do not edit by hand.** To regenerate:\n")
    w("```bash\npython .claude/skills/validate-against-binary/scripts/validate_all.py\n"
      "python .claude/skills/validate-against-binary/scripts/inline_catalogue.py --out docs/ai/InlineCatalogue.md\n```\n")
    w(f"Functions with findings: {sum(1 for r in recs if r['findings'])} ({100 * sum(1 for r in recs if r['findings']) / max(1, len(recs)):.1f}%), "
      f"only CHECK items: {sum(1 for r in recs if not r['findings'] and r['checks'])}, clean: {sum(1 for r in recs if not r['findings'] and not r['checks'])}.\n")

    w("## 1. Functions the original inlines\n")
    w("Our code calls these hooked functions in places where the original has **no call**, because MSVC inlined them. "
      "When a decompilation shows their body, call the function. Don't re-type it, and don't treat it as a missing call.\n")
    w("| Function | Reversed functions where it is inlined | Examples |\n|---|---:|---|")
    for name, n in inlined.most_common(args.top):
        w(f"| `{name}` | {n} | {', '.join(f'`{x}`' for x in inlined_where[name])} |")
    w("")

    w("## 2. Small helpers not in the repo\n")
    w("These are tiny functions (no calls) that the original calls and the repo doesn't name. Most are CVector/CMatrix "
      "operators, getters or constructors of PODs, which C++ expresses with operators or inline code.\n")
    w("| Address | IDB name | Size | Called by N reversed functions |\n|---|---|---|---:|")
    for a, n in helpers.most_common(args.top):
        w(f"| `0x{a}` | `{idb.get(int(a, 16), '?')}` | {helper_info[a]} | {n} |")
    w("")

    w("## 3. CRT functions called by the original\n")
    w("| CRT function | Reversed functions using it | C++ equivalent |\n|---|---:|---|")
    for name, n in crt.most_common(args.top):
        w(f"| `{name}` | {n} | {CRT_HINTS.get(name, '')} |")
    w("")

    w("## 4. Globals referenced by reversed code with no `StaticRef` yet\n")
    w("Add `static inline auto& x = StaticRef<T>(0xADDR);` (type from IDA) and use it.\n")
    w("| Address | IDB name | Referenced by N functions |\n|---|---|---:|")
    for a, n in globals_.most_common(args.top * 2):
        w(f"| `0x{a}` | `{global_info[a]}` | {n} |")
    w("")

    w("## 5. Remaining precision mismatches\n")
    w("Constants in our code that differ from the binary by more than 2 ULP. Use the exact value the binary uses.\n")
    w("| Function | Where | Binary constant | Ours | ULP |\n|---|---|---|---|---:|")
    for name, where, val, (ours, ulp) in sorted(precision, key=lambda x: x[0] or ""):
        w(f"| `{name}` | `{where}` | `{val.split(' (at')[0]}` | `{ours}` | {ulp} |")
    w("")

    text = "\n".join(out)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
