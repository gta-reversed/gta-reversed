#!/usr/bin/env python3
"""
List functions that are still NOT reversed in gta-reversed.

Data sources (combined):
  1. `RH_Scoped*Install(...)` lines in `source/` that carry `.Reversed = false`
     -> gives file, line, function name and GTA address.
  2. `docs/hooks.json` (generated by CI with `--dump-hooks-to`)
     -> gives Category / Name / IsReversed for every registered hook.

Usage (run from the repo root):
  python .claude/skills/find-reversing-targets/scripts/list_unreversed.py               # summary per file (most missing first)
  python .claude/skills/find-reversing-targets/scripts/list_unreversed.py --top 15      # only 15 files
  python .claude/skills/find-reversing-targets/scripts/list_unreversed.py --filter Ped  # path/category substring filter
  python .claude/skills/find-reversing-targets/scripts/list_unreversed.py --details     # list every function
  python .claude/skills/find-reversing-targets/scripts/list_unreversed.py --almost-done # files with only 1-3 missing (quick wins)
  python .claude/skills/find-reversing-targets/scripts/list_unreversed.py --json        # machine readable

Only the standard library is used.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

INSTALL_RE = re.compile(
    r"^\s*(?P<macro>RH_Scoped(?:Global|Named|NamedGlobal|VMT|VMTOverloaded|Overloaded|GlobalOverloaded|Virtual|VirtualOverloaded|Vmt|NamedVMT)?Install)"
    r"\(\s*(?P<fn>[A-Za-z_~][\w:<>]*)\s*,"
)
ADDR_RE = re.compile(r"\b0x[0-9A-Fa-f]{5,8}\b")
NOT_REVERSED_RE = re.compile(r"\.Reversed\s*=\s*false")
OVERLOAD_SUFFIX_RE = re.compile(r"^\s*RH_Scoped\w*Overloaded\w*Install\(\s*\w+\s*,\s*\"(?P<suffix>[^\"]*)\"")


def find_repo_root(start: Path) -> Path:
    for p in [start, *start.parents]:
        if (p / "source" / "InjectHooksMain.cpp").exists():
            return p
    sys.exit("error: run this from inside the gta-reversed repository")


def scan_sources(root: Path) -> list[dict]:
    """Return every RH install line that is marked `.Reversed = false`."""
    results = []
    for path in sorted((root / "source").rglob("*.cpp")):
        try:
            lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            continue
        for i, line in enumerate(lines, 1):
            stripped = line.lstrip()
            if stripped.startswith("//"):
                continue  # commented-out installs are not registered at all
            m = INSTALL_RE.match(line)
            if not m or not NOT_REVERSED_RE.search(line):
                continue
            addr = ADDR_RE.search(line)
            suffix = OVERLOAD_SUFFIX_RE.match(line)
            name = m.group("fn") + (f"-{suffix.group('suffix')}" if suffix and suffix.group("suffix") else "")
            results.append({
                "file": path.relative_to(root).as_posix(),
                "line": i,
                "function": name,
                "address": addr.group(0) if addr else None,
                "virtual": "VMT" in m.group("macro") or "Virtual" in m.group("macro") or "Vmt" in m.group("macro"),
            })
    return results


def total_installs_per_file(root: Path) -> dict[str, int]:
    totals: dict[str, int] = defaultdict(int)
    for path in (root / "source").rglob("*.cpp"):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        n = sum(1 for l in text.splitlines() if not l.lstrip().startswith("//") and INSTALL_RE.match(l))
        if n:
            totals[path.relative_to(root).as_posix()] = n
    return totals


def load_hooks_json(root: Path) -> list[dict]:
    p = root / "docs" / "hooks.json"
    if not p.exists():
        return []
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return []


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--filter", default="", help="case-insensitive substring filter on file path / function name")
    ap.add_argument("--top", type=int, default=0, help="only show N files")
    ap.add_argument("--details", action="store_true", help="list every unreversed function")
    ap.add_argument("--almost-done", action="store_true", help="only files with 1-3 unreversed functions (quick wins)")
    ap.add_argument("--json", action="store_true", help="print JSON")
    args = ap.parse_args()

    root = find_repo_root(Path.cwd())
    items = scan_sources(root)
    flt = args.filter.lower()
    if flt:
        items = [x for x in items if flt in x["file"].lower() or flt in x["function"].lower()]

    by_file: dict[str, list[dict]] = defaultdict(list)
    for it in items:
        by_file[it["file"]].append(it)

    totals = total_installs_per_file(root)
    files = sorted(by_file.items(), key=lambda kv: (-len(kv[1]), kv[0]))
    if args.almost_done:
        files = [kv for kv in files if 1 <= len(kv[1]) <= 3]
        files.sort(key=lambda kv: (len(kv[1]), -totals.get(kv[0], 0)))
    if args.top:
        files = files[: args.top]

    if args.json:
        print(json.dumps({f: v for f, v in files}, indent=2))
        return

    hooks = load_hooks_json(root)
    if hooks:
        done = sum(1 for h in hooks if h.get("IsReversed"))
        print(f"docs/hooks.json: {done}/{len(hooks)} hooks reversed ({100 * done / len(hooks):.1f}%) "
              f"- note: it is only refreshed by CI, may be stale\n")

    print(f"{len(items)} unreversed hook installs (`.Reversed = false`) in {len(by_file)} files"
          + (f" matching '{args.filter}'" if flt else "") + "\n")
    print(f"{'missing':>7} {'total':>5}  file")
    for f, fns in files:
        print(f"{len(fns):>7} {totals.get(f, 0):>5}  {f}")
        if args.details or args.almost_done:
            for fn in sorted(fns, key=lambda x: x["line"]):
                kind = "virtual" if fn["virtual"] else "static "
                print(f"{'':>15}{fn['address'] or '??????':>10}  {kind}  {fn['function']}  ({f}:{fn['line']})")


if __name__ == "__main__":
    main()
