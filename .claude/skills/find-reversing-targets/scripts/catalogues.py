#!/usr/bin/env python3
"""
Generates lookup catalogues in docs/ai/ from the IDB exports, gta_sa.exe and the repository:

  docs/ai/Vtables.md         every class registered with RH_ScopedVirtualClass: vtable address, slot count, and each
                             slot the class adds or overrides (address, IDB name, repo status)
  docs/ai/Globals.md         game globals referenced by game code: address, IDB/repo name, type, how many functions
                             read/write it, top users; split into "already a StaticRef in the repo" and "not yet"
  docs/ai/Enums.md           enums in the IDB, whether the repo has an enum with the same name, members of the missing ones
  docs/ai/FrameCallGraph.md  call tree of the per-frame entry points (Idle, CGame::Process, RenderScene...) with the
                             status of each function and the unreversed bytes below it

Inputs (refresh them first when the IDB or repo changed a lot):
  python .claude/skills/find-reversing-targets/scripts/ida_rpc.py export        # .claude/cache/idb_export.json
  python .claude/skills/find-reversing-targets/scripts/ida_rpc.py export-xrefs  # .claude/cache/xrefs_export.json
  gta_sa.exe path in .claude/gtasa_exe_path.txt (or GTASA_EXE) - used to read vtable slots

Run:
  python .claude/skills/find-reversing-targets/scripts/catalogues.py [--only vtables,globals,enums,callgraph] [--depth 3]
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(REPO / ".claude" / "skills" / "validate-against-binary" / "scripts"))
from asm_validate import PEImage, Repo  # noqa: E402
from idb_coverage import is_game_region_function, region_of, repo_status  # noqa: E402

CACHE = REPO / ".claude" / "cache"
OUT_DIR = REPO / "docs" / "ai"
VCLASS_RE = re.compile(r"RH_ScopedVirtualClass\(\s*(?P<cls>[\w:<>, ]+?)\s*,\s*(?P<addr>0x[0-9A-Fa-f]+)\s*,\s*(?P<n>\d+)\s*\)")
BASE_RE = re.compile(r"^\s*(?:class|struct)\s+(?:NOTSA_\w+\s+)?(?P<cls>\w+)\s*(?:final\s*)?:\s*(?:public\s+)?(?P<base>[\w:]+)", re.M)
ENUM_RE = re.compile(r"\benum\s+(?:class\s+|struct\s+)?(?P<name>\w+)")
GENERATED = ("Generated by `.claude/skills/find-reversing-targets/scripts/catalogues.py` from the IDB exports, gta_sa.exe and "
             "the repository. **Do not edit by hand**; regenerate it (see the script's docstring) when the repo changes.")
FRAME_ROOTS = ["Idle", "FrontendIdle", "CGame::Process", "RenderScene", "RenderEffects", "Render2dStuff", "RenderMenus"]


def load_json(name: str) -> dict:
    p = CACHE / name
    if not p.exists():
        sys.exit(f"missing {p} - run ida_rpc.py {'export' if name == 'idb_export.json' else 'export-xrefs'} first")
    return json.loads(p.read_text(encoding="utf-8"))


def load_pe() -> PEImage | None:
    cand = os.environ.get("GTASA_EXE")
    cfg = REPO / ".claude" / "gtasa_exe_path.txt"
    if not cand and cfg.exists():
        cand = cfg.read_text(encoding="utf-8").strip()
    return PEImage(Path(cand)) if cand and Path(cand).exists() else None


def short(dname: str | None, ea: int) -> str:
    return (dname or f"sub_{ea:X}").split("(")[0]


class Ctx:
    def __init__(self) -> None:
        self.idb = load_json("idb_export.json")
        self.funcs = {f["ea"]: f for f in self.idb["funcs"]}
        print("indexing repo...", file=sys.stderr)
        self.repo = Repo(REPO)
        self.status = repo_status(self.repo)

    def fname(self, ea: int) -> str:
        f = self.funcs.get(ea)
        return short(f["dname"], ea) if f else f"sub_{ea:X}"

    def fstatus(self, ea: int) -> str:
        return self.status.get(ea, "MISSING")


# ---------------------------------------------------------------- vtables
def gen_vtables(ctx: Ctx) -> str:
    pe = load_pe()
    if not pe:
        return "# Vtables\n\ngta_sa.exe not configured (.claude/gtasa_exe_path.txt) - can't read the slots.\n"
    classes: dict[str, tuple[int, int, str]] = {}
    bases: dict[str, str] = {}
    for rel, text in ctx.repo.stripped.items():
        for m in VCLASS_RE.finditer(text):
            cls = m.group("cls").strip()
            classes.setdefault(cls, (int(m.group("addr"), 16), int(m.group("n")), rel))
        if rel.endswith((".h", ".hpp")):
            for m in BASE_RE.finditer(text):
                bases.setdefault(m.group("cls"), m.group("base").split("::")[-1])
    slots = {cls: [pe.read_u32(vt + 4 * i) for i in range(n)] for cls, (vt, n, _) in classes.items()}

    rows, details = [], []
    totals = defaultdict(int)
    for cls in sorted(classes, key=str.lower):
        vt, n, rel = classes[cls]
        bare = cls.split("::")[-1].split("<")[0]
        base = bases.get(bare)
        inherited: set[int] = set()
        anc, guard = base, 0
        while anc and guard < 12:  # every ancestor, registered or not
            inherited.update(slots.get(anc, []))
            anc, guard = bases.get(anc), guard + 1

        def is_own(i: int, a: int) -> bool:
            if not a or a in inherited:
                return False
            owner = ctx.fname(a).rsplit("::", 1)[0] if "::" in ctx.fname(a) else None
            # slot implemented by a named ancestor (eg. CTaskSimple::GetSubTask) even if that ancestor isn't registered
            return i == 0 or owner is None or owner.split("::")[-1] == bare or owner not in ancestors

        ancestors, anc = set(), base
        while anc and len(ancestors) < 12:
            ancestors.add(anc)
            anc = bases.get(anc)
        own = [(i, a) for i, a in enumerate(slots[cls]) if is_own(i, a)]
        st = defaultdict(int)
        for _, a in own:
            st[ctx.fstatus(a)] += 1
        for k, v in st.items():
            totals[k] += v
        rows.append(f"| [`{cls}`](#{re.sub(r'[^a-z0-9_-]', '', cls.lower())}) | `{vt:#x}` | {n} | {base or '-'} | {len(own)} | "
                    f"{st['REVERSED']} | {st['STUB']} | {st['NOHOOK'] + st['KNOWN'] + st['MISSING']} |")
        details.append(f"### {cls}\n\n`{vt:#x}`, {n} slots, base `{base or '-'}`, registered in `{rel}`."
                       + (f" {n - len(own)} slots are inherited from an ancestor and are not repeated." if n != len(own) else "") + "\n")
        if own:
            details.append("| Slot | Address | IDB name | Status |\n|---:|---|---|---|")
            for i, a in own:
                st_ = ctx.fstatus(a)
                note = " (slot 0 is the scalar deleting destructor; the repo hooks the plain destructor instead)" if i == 0 and st_ != "REVERSED" else ""
                details.append(f"| {i} | `{a:#x}` | `{ctx.fname(a)}` | {st_}{note} |")
        details.append("")
    head = (f"# Vtables\n\n{GENERATED}\n\n"
            f"{len(classes)} classes registered with `RH_ScopedVirtualClass(cls, vtable, slots)`. Slots are read from gta_sa.exe. "
            "A slot is listed under a class only when its address differs from the base class's vtable (the base is taken "
            "from the class declaration). Use this to check `RH_ScopedVMTInstall` addresses: an address that is not in the "
            "class's vtable makes `VMTInfo` throw at start-up.\n\n"
            f"Own slots across all classes: {totals['REVERSED']} reversed, {totals['STUB']} stub, "
            f"{totals['NOHOOK'] + totals['KNOWN'] + totals['MISSING']} not hooked.\n\n"
            "| Class | Vtable | Slots | Base | Own slots | Reversed | Stub | Not hooked |\n|---|---|---:|---|---:|---:|---:|---:|\n")
    return head + "\n".join(rows) + "\n\n## Slots per class\n\n" + "\n".join(details)


# ---------------------------------------------------------------- globals
def gen_globals(ctx: Ctx, xr: dict) -> str:
    names = {n["ea"]: n for n in ctx.idb["names"]}
    game_fn = {f["ea"] for f in ctx.idb["funcs"] if is_game_region_function(f)}
    in_repo, not_repo = [], []
    for g in xr["globals"]:
        users = [u for u in g["funcs"] if u in game_fn]
        if not users:
            continue
        n = names.get(g["ea"], {})
        sym = ctx.repo.globals_.get(g["ea"])
        top = ", ".join(f"`{ctx.fname(u)}`" for u in users[:3])
        typ = (n.get("type") or "").replace("|", "\\|")
        row = ((g["nfuncs"], f"| `{g['ea']:#x}` | `{sym.name}` | `{typ}` | {g['nfuncs']} | {g['writes']} |") if sym else
               (g["nfuncs"], f"| `{g['ea']:#x}` | `{g['dname']}` | `{typ}` | {n.get('size') or ''} | "
                             f"{g['nfuncs']} | {g['reads']} | {g['writes']} | {top} |"))
        (in_repo if sym else not_repo).append(row)
    hdr_new = "| Address | IDB name | IDB type | Size | Functions | Reads | Writes | Used by (first 3) |\n|---|---|---|---:|---:|---:|---:|---|"
    hdr_repo = "| Address | Repo name | IDB type | Functions | Writes |\n|---|---|---|---:|---:|"
    def table(rows, hdr): return hdr + "\n" + "\n".join(r for _, r in sorted(rows, key=lambda r: -r[0]))
    return (f"# Game globals\n\n{GENERATED}\n\n"
            f"Named items in the data segments that at least one game function reads or writes ({len(in_repo) + len(not_repo)}). "
            "\"Functions\" is how many functions reference the global; reads/writes count instructions. Sorted by number of "
            "functions, so the most shared state comes first.\n\n"
            "Before adding a global, look it up here: take the address and type from this table, declare it with "
            "`static inline auto& ms_X = StaticRef<T>(0xADDR);` (or `StaticRef<T, 0xADDR>()`), never guess.\n\n"
            f"## Not yet in the repository ({len(not_repo)})\n\n{table(not_repo, hdr_new)}\n\n"
            f"## Already a StaticRef in the repository ({len(in_repo)})\n\n{table(in_repo, hdr_repo)}\n")


# ---------------------------------------------------------------- enums
def gen_enums(ctx: Ctx, xr: dict) -> str:
    repo_enums = set()
    for text in ctx.repo.stripped.values():
        repo_enums.update(m.group("name") for m in ENUM_RE.finditer(text))
    have, missing = [], []
    for e in sorted(xr["enums"], key=lambda e: e["name"].lower()):
        if re.match(r"^(enum_\d+|\$[0-9A-F]+|_?D3D|D3DX|Rw|Rp|Rt|_?MIDL|tag[A-Z]|_[A-Z]{2,}|__|_FilterState|MACRO_|DSBCAPS|EAX|"
                    r"EXCEPTION_|CustomGTAWM|gta_shit|floats$)", e["name"]) or "Android" in e["name"]:
            continue
        (have if e["name"] in repo_enums else missing).append(e)
    out = [f"# Enums\n\n{GENERATED}\n\n"
           f"Enums defined in the IDB (RenderWare/D3D/Windows enums filtered out): {len(have)} also exist in the repo under the "
           f"same name, {len(missing)} do not. The members of the missing ones are listed so they can be ported. IDB enum "
           "names can differ from the repo's: search the repo for a member name before adding a duplicate.\n",
           f"## In the IDB only ({len(missing)})\n"]
    for e in missing:
        out.append(f"### {e['name']} ({len(e['members'])} members, {e['size']} bytes)\n")
        mem = e["members"]
        out.append(", ".join(f"`{n}` = {v}" for n, v in mem[:80]) + (f", ... ({len(mem) - 80} more)" if len(mem) > 80 else "") + "\n")
    out.append(f"## Also in the repo ({len(have)})\n")
    out.append(", ".join(f"`{e['name']}`" for e in have) + "\n")
    return "\n".join(out)


# ---------------------------------------------------------------- call graph
def gen_callgraph(ctx: Ctx, xr: dict, depth: int) -> str:
    calls = {int(k, 16): [int(v, 16) for v in vs] for k, vs in xr["calls"].items()}
    by_name = defaultdict(list)
    for f in ctx.idb["funcs"]:
        by_name[short(f["dname"], f["ea"])].append(f["ea"])

    def game(ea):
        f = ctx.funcs.get(ea)
        return bool(f) and is_game_region_function(f)

    left_cache: dict[int, tuple[int, int]] = {}

    def subtree_left(ea: int) -> tuple[int, int]:
        """(unreversed bytes, functions) in the whole reachable game subtree, each function counted once."""
        if ea in left_cache:
            return left_cache[ea]
        seen, stack, b, n = {ea}, [ea], 0, 0
        while stack:
            x = stack.pop()
            if ctx.fstatus(x) != "REVERSED":
                b += ctx.funcs[x]["size"] if x in ctx.funcs else 0
                n += 1
            for c in calls.get(x, []):
                if c not in seen and game(c):
                    seen.add(c)
                    stack.append(c)
        left_cache[ea] = (b, n)
        return b, n

    lines = []
    printed: set[int] = set()

    def walk(ea: int, d: int, prefix: str) -> None:
        f = ctx.funcs.get(ea, {})
        b, n = subtree_left(ea)
        mark = "" if ctx.fstatus(ea) == "REVERSED" else " **"
        info = f"{ctx.fname(ea)} `{ea:#x}` {f.get('size', '?')} B [{ctx.fstatus(ea)}]"
        if d > 0 and b == 0 and ctx.fstatus(ea) == "REVERSED":
            return  # fully reversed subtree: nothing to do there, keep the tree short
        if d > 0 and ea in root_eas:
            lines.append(f"{prefix}{info} (own tree below)")
            return
        if ea in printed:
            lines.append(f"{prefix}{info} (expanded above)")
            return
        printed.add(ea)
        lines.append(f"{prefix}{info}{mark} - below: {n} unreversed / {b:,} B")
        if d >= depth:
            return
        kids = [c for c in calls.get(ea, []) if game(c)]
        for c in kids:
            walk(c, d + 1, prefix + "    ")

    root_eas = {ea for r in FRAME_ROOTS for ea in by_name.get(r, [])}
    for root in FRAME_ROOTS:
        for ea in by_name.get(root, []):
            lines.append("")
            walk(ea, 0, "")
    worst = [a for a in sorted(printed, key=lambda a: -(ctx.funcs.get(a, {}).get("size", 0))) if ctx.fstatus(a) != "REVERSED"][:40]
    return (f"# Per-frame call graph\n\n{GENERATED}\n\n"
            f"Direct calls from the per-frame entry points ({', '.join(FRAME_ROOTS)}), {depth} levels deep, game functions "
            "only (RenderWare/CRT calls are hidden). Each line: name, address, size, status (see `docs/BinaryMap.md` §2), and "
            "for the whole reachable subtree the number of functions and bytes that are not REVERSED yet. Fully reversed subtrees are omitted. Lines ending in "
            "`**` are not reversed themselves. A function already shown is not expanded again.\n\n"
            "Use it to find work that runs every frame (high impact, easy to test in game) and to see what a function "
            "depends on before reversing it.\n\n"
            "## Biggest unreversed functions on these paths\n\n| Function | Address | Size | Status |\n|---|---|---:|---|\n"
            + "\n".join(f"| `{ctx.fname(a)}` | `{a:#x}` | {ctx.funcs[a]['size']} | {ctx.fstatus(a)} |" for a in worst if a in ctx.funcs)
            + "\n\n## Tree\n\n```text" + "\n".join(lines) + "\n```\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", default="vtables,globals,enums,callgraph")
    ap.add_argument("--depth", type=int, default=3)
    ap.add_argument("--out-dir", default=str(OUT_DIR))
    a = ap.parse_args()
    only = set(a.only.split(","))
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    ctx = Ctx()
    xr = load_json("xrefs_export.json") if only & {"globals", "enums", "callgraph"} else {}
    jobs = {"vtables": ("Vtables.md", lambda: gen_vtables(ctx)),
            "globals": ("Globals.md", lambda: gen_globals(ctx, xr)),
            "enums": ("Enums.md", lambda: gen_enums(ctx, xr)),
            "callgraph": ("FrameCallGraph.md", lambda: gen_callgraph(ctx, xr, a.depth))}
    for key in ("vtables", "globals", "enums", "callgraph"):
        if key in only:
            fn, gen = jobs[key]
            text = gen()
            (out / fn).write_text(text, encoding="utf-8")
            print(f"wrote {out / fn} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
